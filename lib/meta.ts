/** Хвост, который шаблон в `app/layout.tsx` дописывает к каждому заголовку. */
const SUFFIX = " — клиника AURUM".length;

/** Заголовки длиннее этого выдача обрезает многоточием. */
const LIMIT = 65;

/**
 * Укладывает заголовок страницы в лимит выдачи вместе с хвостом шаблона.
 *
 * Варианты перебираются по порядку — от самого информативного к самому
 * короткому, берётся первый, который влезает. Если не влезает ни один,
 * возвращается последний: он короче остальных, и обрезка съест меньше.
 * H1 на самой странице всегда остаётся полным — сокращение живёт только
 * в `<title>`.
 */
export function fitTitle(...variants: string[]) {
  const fits = variants.find((v) => v.length + SUFFIX <= LIMIT);
  return fits ?? variants[variants.length - 1];
}
